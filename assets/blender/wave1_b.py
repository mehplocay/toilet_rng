def puff(name, loc, scale, color, detail=10, rings=6, smooth=True):
    return sphere(name, loc, scale, color, detail, rings, smooth)


def small(name, loc, scale, color):
    return puff(name, loc, scale, color, 8, 4)


def softbox(name, loc, size, color, bevel=.04):
    """Single bevel segment for small trim; retain the shared palette mapping."""
    bpy.ops.mesh.primitive_cube_add(size=1,location=loc)
    obj=bpy.context.object
    obj.name=name
    obj.scale=size
    bpy.ops.object.transform_apply(location=False,rotation=False,scale=True)
    mod=obj.modifiers.new('Small molded edge','BEVEL')
    mod.width=min(bevel,min(size)*.45)
    mod.segments=1
    return finish(obj,color,False)


def line(name, points, radius, color, sides=6):
    return tube(name, points, [radius]*len(points), color, sides)


