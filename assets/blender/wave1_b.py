def towel_band(radius, z, phase):
    # A broad helical ribbon with rounded rectangular cross section, not a hose.
    verts=[]
    steps=18
    section=[(-.075,-.19),(.075,-.19),(.11,-.13),(.11,.13),(.075,.19),(-.075,.19),(-.11,.13),(-.11,-.13)]
    for i in range(steps+1):
        t=i/steps
        a=phase+t*math.tau*1.08
        r=radius+.13*t
        for dr,dz in section:
            verts.append(((r+dr)*math.cos(a),(r+dr)*math.sin(a),z+t*.59+dz))
    faces=[tuple(reversed(range(8))),tuple(steps*8+j for j in range(8))]
    for i in range(steps):
        for j in range(8):
            k=i*8+j
            faces.append((k,i*8+(j+1)%8,(i+1)*8+(j+1)%8,k+8))
    mesh("Thick folded spiral towel band",verts,faces,"mint",True)
    pts=[]
    for i in range(steps+1):
        t=i/steps
        a=phase+t*math.tau*1.08
        r=radius+.13*t+.09
        pts.append((r*math.cos(a),r*math.sin(a),z+t*.59-.15))
    line("Cream towel hem",pts,.03,"cream",4)


